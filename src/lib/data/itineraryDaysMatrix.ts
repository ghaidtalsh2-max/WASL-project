// Helper to sanitize array to requested day count
export function buildCustomDays(
  destinationName: string,
  cityName: string,
  totalDays: number,
  style: 'balanced' | 'relaxed'
): TourismOptionDay[] {
  const normDest = (destinationName || '').toLowerCase();
  const city = cityName || 'Central District';
  const combined = `${normDest} ${city.toLowerCase()}`;

  if (
    combined.includes('united states') ||
    combined.includes('usa') ||
    combined.includes('us') ||
    combined.includes('america') ||
    combined.includes('أمريكا') ||
    combined.includes('orlando') ||
    combined.includes('أورلاندو') ||
    combined.includes('florida') ||
    combined.includes('فلوريدا') ||
    combined.includes('miami') ||
    combined.includes('ميامي') ||
    combined.includes('california') ||
    combined.includes('los angeles') ||
    combined.includes('new york')
  ) {
    return style === 'balanced' ? getUSPlanADays(totalDays, city) : getUSPlanBDays(totalDays, city);
  }

  if (normDest.includes('turkey') || normDest.includes('تركيا') || normDest.includes('istanbul') || normDest.includes('إسطنبول')) {
    return style === 'balanced' ? getTurkeyPlanADays(totalDays, city) : getTurkeyPlanBDays(totalDays, city);
  }

  if (normDest.includes('egypt') || normDest.includes('مصر') || normDest.includes('cairo') || normDest.includes('القاهرة')) {
    return style === 'balanced' ? getEgyptPlanADays(totalDays, city) : getEgyptPlanBDays(totalDays, city);
  }

  if (normDest.includes('morocco') || normDest.includes('المغرب') || normDest.includes('marrakech') || normDest.includes('مراكش')) {
    return style === 'balanced' ? getMoroccoPlanADays(totalDays, city) : getMoroccoPlanBDays(totalDays, city);
  }

  if (normDest.includes('mauritius') || normDest.includes('موريشيوس')) {
    return style === 'balanced' ? getMauritiusPlanADays(totalDays, city) : getMauritiusPlanBDays(totalDays, city);
  }

  if (normDest.includes('japan') || normDest.includes('اليابان') || normDest.includes('tokyo') || normDest.includes('طوكيو') || normDest.includes('osaka') || normDest.includes('أوساكا') || normDest.includes('kyoto') || normDest.includes('كيوتو')) {
    return style === 'balanced' ? getJapanPlanADays(totalDays, city) : getJapanPlanBDays(totalDays, city);
  }

  if (normDest.includes('czech') || normDest.includes('التشيك') || normDest.includes('تشيك') || normDest.includes('prague') || normDest.includes('براغ')) {
    return style === 'balanced' ? getCzechPlanADays(totalDays, city) : getCzechPlanBDays(totalDays, city);
  }

  if (normDest.includes('saudi') || normDest.includes('السعودية') || normDest.includes('riyadh') || normDest.includes('الرياض')) {
    return style === 'balanced' ? getSaudiPlanADays(totalDays, city) : getSaudiPlanBDays(totalDays, city);
  }

  return style === 'balanced' ? getUniversalPlanADays(totalDays, city, destinationName) : getUniversalPlanBDays(totalDays, city, destinationName);
}

